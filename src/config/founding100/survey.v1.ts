import { Question, ConsentState } from '../../types/research';

export function hasSymptomsSelected(c01Answer: any): boolean {
  if (!c01Answer) return false;
  const list = Array.isArray(c01Answer) ? c01Answer : c01Answer.selection || [];
  if (list.length === 0) return false;
  if (list.includes('none_of_these') || list.includes('prefer_not')) return false;
  return true;
}

export function shouldShowContact(answers: Record<string, any>, consents: ConsentState): boolean {
  const g01 = answers.G01;
  const interestedInFounding100 = g01 === 'yes' || g01 === 'learn_more';
  return interestedInFounding100 || consents.consent_contact || consents.consent_updates;
}

